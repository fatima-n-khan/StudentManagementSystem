    private void btnCalculateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalculateActionPerformed
                                    
    String value1 = txtGpa1.getText().trim();
    String value2 = txtGpa2.getText().trim();
    String value3 = txtGpa3.getText().trim();
    String value4 = txtGpa4.getText().trim();

    // Check empty fields
    if (value1.isEmpty() || value2.isEmpty() ||
        value3.isEmpty() || value4.isEmpty()) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please enter all four GPA values.",
                "Input Required",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    try {

        double gpa1 = Double.parseDouble(value1);
        double gpa2 = Double.parseDouble(value2);
        double gpa3 = Double.parseDouble(value3);
        double gpa4 = Double.parseDouble(value4);

        // Check GPA range
        if (gpa1 < 0 || gpa1 > 4 ||
            gpa2 < 0 || gpa2 > 4 ||
            gpa3 < 0 || gpa3 > 4 ||
            gpa4 < 0 || gpa4 > 4) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "GPA must be between 0.0 and 4.0.",
                    "Invalid GPA",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        // Calculate CGPA
        double cgpa = (gpa1 + gpa2 + gpa3 + gpa4) / 4;

        lblResult.setText(String.format("CGPA: %.2f", cgpa));

    } catch (NumberFormatException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please enter valid numeric GPA values.",
                "Invalid Input",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );
    }

    }//GEN-LAST:event_btnCalculateActionPerformed

