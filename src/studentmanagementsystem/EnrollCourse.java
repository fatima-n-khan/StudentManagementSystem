    private void btnEnrollActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEnrollActionPerformed

    String studentId = txtStudentId.getText().trim();
    String courseName = txtCourseName.getText().trim();
    
    // Negative Student ID validation
    if (studentId.contains("-")) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Negative Student ID is not allowed!",
                "Invalid ID",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );

        return;
    }

if (studentId.isEmpty() || courseName.isEmpty()) {
    JOptionPane.showMessageDialog(
        this,
        "Please enter Student ID and Course Name."
    );
    return;
}

// Check if student exists
boolean studentFound = false;

for (Student s : Dashboard.studentList) {
    if (s.getId().equalsIgnoreCase(studentId)) {
        studentFound = true;
        break;
    }
}

if (!studentFound) {
    JOptionPane.showMessageDialog(
        this,
        "Student ID not found. Please add the student first."
    );
    return;
}

// Check for duplicate enrollment
for (Enrollment e : Dashboard.enrollmentList) {
    if (e.getStudentId().equalsIgnoreCase(studentId)
            && e.getCourseName().equalsIgnoreCase(courseName)) {

        JOptionPane.showMessageDialog(
            this,
            "This student is already enrolled in this course."
        );
        return;
    }
}

// Add enrollment
Dashboard.enrollmentList.add(
    new Enrollment(studentId, courseName)
);

JOptionPane.showMessageDialog(
    this,
    "Course enrolled successfully!"
);

txtStudentId.setText("");
txtCourseName.setText("");
    }//GEN-LAST:event_btnEnrollActionPerformed

