    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed

    String studentId = txtStudentId.getText().trim();
String title = txtTitle.getText().trim();

// Check empty fields
if (studentId.isEmpty() || title.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please fill in all fields.",
            "Input Required",
            javax.swing.JOptionPane.WARNING_MESSAGE
    );
    return;
}

// Check if a due date is selected
if (dateChooserDueDate.getDate() == null) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please select a due date.",
            "Input Required",
            javax.swing.JOptionPane.WARNING_MESSAGE
    );
    return;
}

// Get selected date
java.util.Date selectedDate = dateChooserDueDate.getDate();

java.time.LocalDate dueDate =
        selectedDate.toInstant()
                .atZone(java.time.ZoneId.systemDefault())
                .toLocalDate();

java.time.LocalDate today =
        java.time.LocalDate.now();

// Due date must be in the future
if (!dueDate.isAfter(today)) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Due date must be a future date.",
            "Invalid Due Date",
            javax.swing.JOptionPane.WARNING_MESSAGE
    );
    return;
}

// Check whether student exists
boolean studentExists = false;

for (Student s : Dashboard.studentList) {
    if (s.getId().equalsIgnoreCase(studentId)) {
        studentExists = true;
        break;
    }
}

if (!studentExists) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Student ID not found!",
            "Invalid Student ID",
            javax.swing.JOptionPane.WARNING_MESSAGE
    );
    return;
}

// Convert selected date to String
String dueDateText = dueDate.toString();

// Create assignment
Assignment a =
        new Assignment(studentId, title, dueDateText);

Dashboard.assignmentList.add(a);

// Success message
javax.swing.JOptionPane.showMessageDialog(
        this,
        "Assignment Added Successfully!",
        "Success",
        javax.swing.JOptionPane.INFORMATION_MESSAGE
);

// Clear fields
txtStudentId.setText("");
txtTitle.setText("");
dateChooserDueDate.setDate(null);

    }//GEN-LAST:event_btnSaveActionPerformed

