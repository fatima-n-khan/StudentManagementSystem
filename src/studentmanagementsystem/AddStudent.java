    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
                                    
    String id = txtId.getText().trim();
    String name = txtName.getText().trim();
    String department = txtDepartment.getText().trim();
    String semester = txtSemester.getText().trim();

    // Student ID validation
if (id.contains("-")) {
    JOptionPane.showMessageDialog(
        this,
        "Negative Student ID is not allowed!",
        "Invalid ID",
        JOptionPane.WARNING_MESSAGE
    );
    return;
}

// If ID contains only numbers, it must be greater than 0
if (id.matches("\\d+")) {
    try {
        if (Integer.parseInt(id) <= 0) {
            JOptionPane.showMessageDialog(
                this,
                "Student ID must be greater than 0!",
                "Invalid ID",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(
            this,
            "Invalid Student ID!",
            "Invalid ID",
            JOptionPane.WARNING_MESSAGE
        );
        return;
    }
}
    
    // Check empty fields
    if (id.isEmpty() || name.isEmpty() || department.isEmpty() || semester.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please fill in all fields.",
                "Input Required",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    // Check duplicate Student ID
    for (Student existingStudent : Dashboard.studentList) {
        if (existingStudent.getId().equalsIgnoreCase(id)) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Student ID already exists!",
                    "Duplicate ID",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );
            return;
        }
    }

    // Add student
    Student s = new Student(id, name, department, semester);
    Dashboard.studentList.add(s);

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Student Added Successfully!",
            "Success",
            javax.swing.JOptionPane.INFORMATION_MESSAGE
    );

    // Clear fields
    txtId.setText("");
    txtName.setText("");
    txtDepartment.setText("");
    txtSemester.setText("");

    }//GEN-LAST:event_btnSaveActionPerformed

