    private void btnCompleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCompleteActionPerformed

        String studentId = txtStudentId.getText().trim();
String title = txtTitle.getText().trim();

// Check empty fields
if (studentId.isEmpty() || title.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please enter Student ID and Assignment Title.",
            "Input Required",
            javax.swing.JOptionPane.WARNING_MESSAGE
    );
    return;
}

boolean found = false;

for (Assignment a : Dashboard.assignmentList) {

    if (a.getStudentId().equalsIgnoreCase(studentId)
            && a.getTitle().equalsIgnoreCase(title)) {

        if (a.getStatus().equalsIgnoreCase("Completed")) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "This assignment is already completed.",
                    "Already Completed",
                    javax.swing.JOptionPane.INFORMATION_MESSAGE
            );
            return;
        }

        a.setStatus("Completed");

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Assignment completed successfully!",
                "Success",
                javax.swing.JOptionPane.INFORMATION_MESSAGE
        );

        txtStudentId.setText("");
        txtTitle.setText("");

        found = true;
        break;
    }
}

if (!found) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Assignment not found for this Student ID.",
            "Not Found",
            javax.swing.JOptionPane.WARNING_MESSAGE
    );
}
    }//GEN-LAST:event_btnCompleteActionPerformed

