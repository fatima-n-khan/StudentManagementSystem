    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
                                
    String searchId = txtSearchId.getText().trim();

    // Check empty search field
    if (searchId.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please enter Student ID.",
                "Input Required",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    boolean found = false;

    for (Student s : Dashboard.studentList) {

        if (s.getId().equalsIgnoreCase(searchId)) {

            txtResult.setText(
                    "ID: " + s.getId() +
                    "\nName: " + s.getName() +
                    "\nDepartment: " + s.getDepartment() +
                    "\nSemester: " + s.getSemester()
            );

            found = true;
            break;
        }
    }

    if (!found) {
        txtResult.setText("Student Not Found");
    }

    }//GEN-LAST:event_jButton1ActionPerformed

