    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
                                 
    String id = txtDeleteId.getText().trim();

    // Check empty ID
    if (id.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please enter Student ID.",
                "Input Required",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    // Find student
    Student studentToDelete = null;

    for (Student s : Dashboard.studentList) {
        if (s.getId().equalsIgnoreCase(id)) {
            studentToDelete = s;
            break;
        }
    }

    // Student not found
    if (studentToDelete == null) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Student not found!",
                "Not Found",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    // Confirmation before deletion
    int choice = javax.swing.JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to delete this student?",
            "Confirm Deletion",
            javax.swing.JOptionPane.YES_NO_OPTION,
            javax.swing.JOptionPane.WARNING_MESSAGE
    );

    if (choice == javax.swing.JOptionPane.YES_OPTION) {

        // Delete student
        Dashboard.studentList.remove(studentToDelete);

        // Remove related enrollments
        Dashboard.enrollmentList.removeIf(
                enrollment -> enrollment.getStudentId().equalsIgnoreCase(id)
        );
        
        Dashboard.assignmentList.removeIf(
            assignment -> assignment.getStudentId().equalsIgnoreCase(id)
        );

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Student deleted successfully!",
                "Success",
                javax.swing.JOptionPane.INFORMATION_MESSAGE
        );

        txtDeleteId.setText("");
    }

    }//GEN-LAST:event_btnDeleteActionPerformed

